export function sectionsFor(reference) {
  return [{ title: PRINCIPLE_TITLE, text: PRINCIPLE }, ...SECTION_TITLES.map((title, i) => ({ title, text: reference.sections[i] })).filter(s => s.text)];
}
export function serializePrompt(sections) {
  return sections.map(({title,text}) => `【${title}】\n${text}`).join('\n\n');
}
export function validateImage(file) {
  if (!file || !['image/png','image/jpeg','image/webp'].includes(file.type)) return '请粘贴静态图片，支持 PNG、JPEG 和 WebP；复制图片地址不会带入图片。';
  if (file.size > 10 * 1024 * 1024) return '图片超过 10 MB，请缩小后重新粘贴。';
  if (!file.size) return '图片内容为空，请重新复制图片。';
  return '';
}
